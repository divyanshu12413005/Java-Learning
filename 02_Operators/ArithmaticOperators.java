//package arithmetic;

public class ArithmaticOperators{
    public static void main(String[] args){

        int p=10;
        int q=50;
        System.out.println("Addition: " + (p + q)); // Addition
        System.out.println("Subtraction: " + (p - q)); // Subtraction
        System.out.println("Multiplication: " + (p * q)); // Multiplication
        System.out.println("Division: " + (p / q)); // Division
        System.out.println("Modulus: " + (p % q)); // Modulus
    }
}